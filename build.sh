#!/bin/zsh
# Build the twin-plate codec and copy the wasm module next to the page.
set -euo pipefail
cd "$(dirname "$0")"
target=wasm32-unknown-unknown
# Homebrew rustc ships the host target only, and its compiler identity will
# not load upstream wasm rust-std. The crate is no_std on wasm and carries
# its own sqrt/sin/floor. Core is built from the rust-src beside this rustc.
# The same formula omits rust-lld. Point that name at Homebrew's ld.lld.
host="$(rustc -vV | awk '/^host:/{print $2}')"
lld_dir="$(rustc --print sysroot)/lib/rustlib/${host}/bin"
if [[ ! -x "$lld_dir/rust-lld" ]]; then
  ld_lld=""
  for candidate in \
    /opt/homebrew/bin/ld.lld \
    /usr/local/bin/ld.lld \
    "$(brew --prefix lld 2>/dev/null)/bin/ld.lld"
  do
    if [[ -n "$candidate" && -x "$candidate" ]]; then
      ld_lld="$candidate"
      break
    fi
  done
  if [[ -z "$ld_lld" ]]; then
    echo "rust-lld is missing. Install the linker with: brew install lld" >&2
    exit 1
  fi
  mkdir -p "$lld_dir"
  printf '#!/bin/sh\nexec %q "$@"\n' "$ld_lld" > "$lld_dir/rust-lld"
  chmod +x "$lld_dir/rust-lld"
fi
RUSTC_BOOTSTRAP=1 cargo build --release --target "$target" \
  -Z build-std=core,compiler_builtins
cp "target/$target/release/twin_plate_vdm.wasm" web/twin_plate_vdm.wasm
python3 - << 'PY'
import base64
from pathlib import Path
wasm = Path("web/twin_plate_vdm.wasm").read_bytes()
out = Path("web/twin_plate_vdm.wasm.js")
# A local script, so opening index.html from Finder does not need a server.
out.write_text(
    "/* generated by build.sh */\nglobalThis.TWIN_WASM_BASE64="
    + repr(base64.b64encode(wasm).decode())
    + ";\n"
)
print(f"wrote {out} ({out.stat().st_size} bytes)")
PY
echo "wrote web/twin_plate_vdm.wasm ($(wc -c < web/twin_plate_vdm.wasm) bytes)"
echo "open web/index.html, or serve it with: python3 -m http.server 8731 --directory web"
